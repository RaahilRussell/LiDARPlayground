import ARKit
import Foundation
import simd

/// JSON-encodable metadata describing a recording.
struct RecordingMetadata: Codable {
    var capturedAt: String
    var deviceModel: String
    var frameTimestamp: Double
    var trackingQuality: String
    var imageWidth: Int
    var imageHeight: Int
    var depthWidth: Int
    var depthHeight: Int
    var depthSource: String
    var intrinsics: [[Float]]        // 3×3, row-major
    var cameraTransform: [[Float]]   // 4×4, row-major
    var poseSampleCount: Int
    var pointCount: Int
    var note: String
}

enum Exporters {

    // MARK: - Public: file builders

    static func depthCSV(matrix: [[Float]]) -> String {
        var lines = [String]()
        lines.reserveCapacity(matrix.count)
        for row in matrix {
            lines.append(row.map { $0 > 0 ? String(format: "%.4f", $0) : "" }.joined(separator: ","))
        }
        return lines.joined(separator: "\n")
    }

    static func poseCSV(samples: [(t: TimeInterval, transform: simd_float4x4)]) -> String {
        var lines = ["timestamp,x,y,z,qx,qy,qz,qw"]
        for s in samples {
            let p = s.transform.columns.3
            let q = simd_quatf(s.transform)
            lines.append(String(format: "%.4f,%.4f,%.4f,%.4f,%.4f,%.4f,%.4f,%.4f",
                                s.t, p.x, p.y, p.z, q.imag.x, q.imag.y, q.imag.z, q.real))
        }
        return lines.joined(separator: "\n")
    }

    static func metadataJSON(_ metadata: RecordingMetadata) -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        return (try? encoder.encode(metadata)) ?? Data()
    }

    /// Writes a sampled point cloud as an ASCII PLY (with per-vertex RGB).
    static func plyData(cloud: PointCloud) -> String {
        var header = """
        ply
        format ascii 1.0
        comment Generated by LiDARPlayground
        element vertex \(cloud.count)
        property float x
        property float y
        property float z
        property uchar red
        property uchar green
        property uchar blue
        end_header

        """
        var body = [String]()
        body.reserveCapacity(cloud.count)
        for i in 0..<cloud.count {
            let p = cloud.positions[i]
            let c = cloud.colors[i]
            let r = UInt8(max(0, min(255, c.x * 255)))
            let g = UInt8(max(0, min(255, c.y * 255)))
            let b = UInt8(max(0, min(255, c.z * 255)))
            body.append(String(format: "%.4f %.4f %.4f %d %d %d", p.x, p.y, p.z, r, g, b))
        }
        header += body.joined(separator: "\n")
        return header
    }

    // MARK: - Temp file helper

    static func writeTemp(_ filename: String, contents: String) -> URL? {
        writeTemp(filename, data: Data(contents.utf8))
    }

    static func writeTemp(_ filename: String, data: Data) -> URL? {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent(filename)
        do {
            try data.write(to: url, options: .atomic)
            return url
        } catch {
            return nil
        }
    }

    // MARK: - Matrix helpers

    static func rows(_ m: simd_float3x3) -> [[Float]] {
        (0..<3).map { r in (0..<3).map { c in m[c][r] } }
    }

    static func rows(_ m: simd_float4x4) -> [[Float]] {
        (0..<4).map { r in (0..<4).map { c in m[c][r] } }
    }
}
